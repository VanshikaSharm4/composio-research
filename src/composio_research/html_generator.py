    def _verdict_badge(self, verdict: str) -> str:
        """Return an HTML badge for a buildability verdict.

        Args:
            verdict: One of "ready", "feasible", "blocked".

        Returns:
            HTML span with appropriate badge class.
        """
        badge_map = {
            "ready": ("badge-green", "Ready"),
            "feasible": ("badge-yellow", "Feasible"),
            "blocked": ("badge-red", "Blocked"),
        }
        css_class, label = badge_map.get(verdict, ("badge-yellow", verdict.title()))
        return f'<span class="{css_class}">{html.escape(label)}</span>'

    def _access_badge(self, access: str) -> str:
        """Return an HTML badge for an access model.

        Args:
            access: One of "self_serve", "gated".

        Returns:
            HTML span with appropriate badge class.
        """
        badge_map = {
            "self_serve": ("badge-blue", "Self-Serve"),
            "gated": ("badge-orange", "Gated"),
        }
        css_class, label = badge_map.get(access, ("badge-orange", access.replace("_", " ").title()))
        return f'<span class="{css_class}">{html.escape(label)}</span>'

    def _evidence_link(self, record: dict[str, Any]) -> str:
        """Return an HTML link to the evidence URL if available."""
        evidence_urls = record.get("evidence_urls", {})
        url = evidence_urls.get("docs_url", "")
        if url:
            short = url.replace("https://", "").replace("http://", "")[:30]
            return f'<a href="{html.escape(url)}" target="_blank" class="text-blue-400 text-xs hover:underline">{html.escape(short)}...</a>'
        return '<span class="text-gray-600 text-xs">N/A</span>'
