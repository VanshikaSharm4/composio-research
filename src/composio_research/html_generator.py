    def _embed_javascript(self, app_records: list[dict[str, Any]]) -> str:
        """Return inline JavaScript with embedded app data and filtering logic.

        Embeds the full app records as a JSON blob and implements:
        - Category filter dropdown
        - Buildability filter dropdown
        - Auth method filter dropdown
        - AND logic for multi-filter combinations
        - Clear-all button
        - "No results" message when no apps match
        - Row count update on filter change

        Args:
            app_records: List of serialized AppRecord dicts.

        Returns:
            HTML <script> block with embedded data and filter logic.
        """
        # Serialize app data for embedding
        json_data = json.dumps(app_records, ensure_ascii=False, separators=(",", ":"))

        return f"""    <script>
    (function() {{
        'use strict';

        const APP_DATA = {json_data};
        const totalApps = APP_DATA.length;

        const filterCategory = document.getElementById('filter-category');
        const filterVerdict = document.getElementById('filter-verdict');
        const filterAuth = document.getElementById('filter-auth');
        const clearBtn = document.getElementById('clear-filters');
        const rowCount = document.getElementById('row-count');
        const noResults = document.getElementById('no-results');
        const noResultsCount = document.getElementById('no-results-count');
        const tableBody = document.getElementById('app-table-body');

        function applyFilters() {{
            const categoryVal = filterCategory ? filterCategory.value : '';
            const verdictVal = filterVerdict ? filterVerdict.value : '';
            const authVal = filterAuth ? filterAuth.value : '';

            const rows = tableBody ? tableBody.querySelectorAll('tr') : [];
            let visibleCount = 0;

            rows.forEach(function(row) {{
                const rowCategory = row.getAttribute('data-category') || '';
                const rowVerdict = row.getAttribute('data-verdict') || '';
                const rowAuth = row.getAttribute('data-auth') || '';

                let show = true;

                if (categoryVal && rowCategory !== categoryVal) {{
                    show = false;
                }}
                if (verdictVal && rowVerdict !== verdictVal) {{
                    show = false;
                }}
                if (authVal) {{
                    const authMethods = rowAuth.split(',');
                    if (authMethods.indexOf(authVal) === -1) {{
                        show = false;
                    }}
                }}

                row.style.display = show ? '' : 'none';
                if (show) visibleCount++;
            }});

            if (rowCount) {{
                rowCount.textContent = 'Showing ' + visibleCount + ' of ' + totalApps + ' apps';
            }}
            if (noResults) {{
                if (visibleCount === 0) {{
                    noResults.classList.remove('hidden');
                    if (noResultsCount) {{
                        noResultsCount.textContent = '0 results';
                    }}
                }} else {{
                    noResults.classList.add('hidden');
                }}
            }}
        }}

        function clearFilters() {{
            if (filterCategory) filterCategory.value = '';
            if (filterVerdict) filterVerdict.value = '';
            if (filterAuth) filterAuth.value = '';
            applyFilters();
        }}

        if (filterCategory) filterCategory.addEventListener('change', applyFilters);
        if (filterVerdict) filterVerdict.addEventListener('change', applyFilters);
        if (filterAuth) filterAuth.addEventListener('change', applyFilters);
        if (clearBtn) clearBtn.addEventListener('click', clearFilters);
    }})();
    </script>"""

